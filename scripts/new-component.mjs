#!/usr/bin/env node
/**
 * Scaffold a new component that follows the project's token convention.
 *
 *   node scripts/new-component.mjs tooltip
 *
 * Creates:
 *   src/components/tooltip/style.css   — semantic tokens + rules, inside @layer components
 *   src/components/tooltip/Tooltip.tsx  — the component itself
 *   src/components/tooltip/index.ts     — barrel
 *
 * And wires it up:
 *   src/style.css            — adds the @import line
 *   src/components/index.ts  — regenerated (uses `export *`)
 */
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const componentsDir = join(root, 'src', 'components')

const raw = (process.argv[2] || '').trim()
if (!raw) {
  console.error('Usage: node scripts/new-component.mjs <component-name>')
  process.exit(1)
}

const kebab = raw
  .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
  .replace(/[\s_]+/g, '-')
  .toLowerCase()
const pascal = kebab
  .split('-')
  .filter(Boolean)
  .map((w) => w[0].toUpperCase() + w.slice(1))
  .join('')

if (!kebab || !pascal) {
  console.error(`"${raw}" does not produce a usable component name.`)
  process.exit(1)
}

const dir = join(componentsDir, kebab)
if (existsSync(dir)) {
  console.error(`Component "${kebab}" already exists at src/components/${kebab}`)
  process.exit(1)
}

mkdirSync(dir, { recursive: true })

/* ── style.css ─────────────────────────────────────────────────────────── */
writeFileSync(
  join(dir, 'style.css'),
  `/*
 * ${pascal} — component-scoped semantic tokens
 * --------------------------------------------------------------------------
 * Every token is namespaced \`--${kebab}-*\` so it can never collide with the
 * global tokens in src/tokens/semantic.css. Values point at the global tokens,
 * so the component re-themes itself when the page switches to dark mode.
 *
 * JSX usage:  <div class="${kebab}">…</div>
 */

@layer components {
  .${kebab} {
    /* ── semantic tokens ─────────────────────────────────────────────── */
    --${kebab}-background: var(--surface);
    --${kebab}-foreground: var(--foreground);
    --${kebab}-border: var(--border);
    --${kebab}-radius: 0.5rem;
    --${kebab}-padding: 0.75rem;
    --${kebab}-gap: 0.5rem;

    /* ── component rules ─────────────────────────────────────────────── */
    display: flex;
    flex-direction: column;
    gap: var(--${kebab}-gap);
    box-sizing: border-box;
    background-color: var(--${kebab}-background);
    color: var(--${kebab}-foreground);
    border: 1px solid var(--${kebab}-border);
    border-radius: var(--${kebab}-radius);
    padding: var(--${kebab}-padding);
  }
}
`,
)

/* ── ${pascal}.tsx ─────────────────────────────────────────────────────── */
writeFileSync(
  join(dir, `${pascal}.tsx`),
  `import type { HTMLAttributes, ReactNode } from 'react'

export interface ${pascal}Props extends HTMLAttributes<HTMLDivElement> {
  children?: ReactNode
}

/**
 * All visual styling lives in ./style.css as semantic tokens.
 * This file only wires the component to its CSS classes.
 */
export function ${pascal}({
  className = '',
  children,
  ...rest
}: ${pascal}Props) {
  return (
    <div className={['${kebab}', className].filter(Boolean).join(' ')} {...rest}>
      {children}
    </div>
  )
}

export default ${pascal}
`,
)

/* ── index.ts ──────────────────────────────────────────────────────────── */
writeFileSync(
  join(dir, 'index.ts'),
  `export { ${pascal} } from './${pascal}'\nexport { default } from './${pascal}'\nexport type { ${pascal}Props } from './${pascal}'\n`,
)

/* ── wire the @import into src/style.css ───────────────────────────────── */
const stylePath = join(root, 'src', 'style.css')
let style = readFileSync(stylePath, 'utf8')
const importLine = `@import "./components/${kebab}/style.css";`
if (!style.includes(importLine)) {
  const marker = '/* 4 ── Tailwind directives'
  if (!style.includes(marker)) {
    console.error('Could not find the component-import section in src/style.css')
    process.exit(1)
  }
  style = style.replace(marker, `${importLine}\n\n${marker}`)
  writeFileSync(stylePath, style)
}

/* ── regenerate src/components/index.ts ────────────────────────────────── */
const names = readFileSync(join(componentsDir, 'index.ts'), 'utf8')
const existing = [...names.matchAll(/export \* from '\.\/([^']+)'/g)].map((m) => m[1])
const all = [...new Set([...existing, kebab])].sort()
writeFileSync(
  join(componentsDir, 'index.ts'),
  `/* Auto-generated by scripts/new-component.mjs — do not edit by hand. */\n${all
    .map((n) => `export * from './${n}'`)
    .join('\n')}\n`,
)

console.log(`✓ Created src/components/${kebab}/`)
console.log(`  ${kebab}/style.css   — semantic tokens inside @layer components`)
console.log(`  ${kebab}/${pascal}.tsx`)
console.log(`  ${kebab}/index.ts`)
console.log(`✓ Added ${importLine} to src/style.css`)
console.log(`✓ Regenerated src/components/index.ts`)
